-- Persisted UI preferences, not player SavedVariables.
local addon={}; assert(loadfile('Core/Database.lua'))('ErrandMaster',addon)
ErrandMasterDB=nil; addon.db:Initialize('tester')
local db=addon.db
local function contains(t,x) for _,v in ipairs(t) do if v==x then return true end end end
assert(#db:GetWheelProfessions()==12, 'unset picks include all classic primaries and commons')
assert(db:SetProfessionPick(1,'Alchemy'))
assert(#db:GetWheelProfessions()==12, 'either unset picker means all')
assert(db:SetProfessionPick(2,'Mining'))
assert(#db:GetWheelProfessions()==5 and contains(db:GetWheelProfessions(),'Fishing'))
assert(db:SetCommonProfession('Cooking',false))
assert(#db:GetWheelProfessions()==4 and not contains(db:GetWheelProfessions(),'Cooking'))
assert(db:SetProfessionPick(2,nil))
assert(#db:GetWheelProfessions()==11, 'all primaries must respect common opt-out')
assert(not db:SetProfessionPick(1,'Unknown'))
assert(not db:SetCommonProfession('Mining',false))
assert(db:SetWheelMetric('wheelRadius',40))
assert(db:SetWheelMetric('wheelScale',.5))
assert(db:SetWheelMetric('wheelIconSize',20))
assert(not db:SetWheelMetric('wheelRadius',0/0))
assert(not db:SetWheelMetric('wheelScale',math.huge))
assert(not db:SetWheelMetric('unrelated',40))
assert(db:WheelInsert({type='folder',name='New menu',entries={}}))
local index=#db.data.settings.wheelSlots
assert(db:WheelSetIcon(index,134400))
assert(db.data.settings.wheelSlots[index].icon==134400)
db:Initialize('tester')
assert(db.data.settings.wheelRadius==40 and db.data.settings.wheelScale==.5)
assert(db.data.settings.wheelIconSize==20)
assert(db.data.settings.wheelSlots[index].icon==134400 and #db.data.settings.wheelSlots[index].entries==0)
assert(not contains(db:GetWheelProfessions(),'Cooking'))
db:Initialize('another'); assert(#db:GetWheelProfessions()==12,'per-character preferences')
assert(not db:WheelInsert({type='category',category='   '}), 'blank categories are rejected')
db:Initialize('legacy');db:AddProfession('alchemy');db:AddProfession('MINING')
local migrated=db:ProfessionPreferences()
assert(migrated.picks[1]=='Alchemy' and migrated.picks[2]=='Mining', 'legacy casing is normalized')
assert(migrated.common.Cooking and migrated.common.Fishing and migrated.common['First Aid'],
  'absence in old positive-only overrides is not evidence of explicit opt-out; requested new defaults apply')
print('UI preference bounds, profession defaults/opt-out and empty/icon folders passed')
local items=db:Bucket('character')
items[1]={manualPosition=2};items[2]={manualPosition=math.huge};items[3]={manualPosition='1'}
db:Initialize('legacy')
assert(items[1].manualPosition==2 and items[2].manualPosition==nil and items[3].manualPosition==nil)
